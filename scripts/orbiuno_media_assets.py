#!/usr/bin/env python3
"""Stage ONLY independently licensed Commons photos and real outlet favicons.

Fail closed when any of the six images lacks verified metadata, image review,
license, credit, or when a source favicon cannot be decoded. Not a publisher.
"""
from __future__ import annotations
import argparse
import html
import io
import json
import re
from datetime import datetime
from pathlib import Path
from urllib.parse import quote, urlencode, urlsplit
from urllib.request import Request, urlopen
from zoneinfo import ZoneInfo

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
LICENSES = {"CC BY 4.0", "CC BY-SA 4.0", "CC BY 3.0", "CC BY-SA 3.0",
            "CC BY 2.0", "CC BY-SA 2.0", "CC0", "CC0 1.0", "Public domain", "PD"}
BAD_TAGS = ("artificial intelligence", "ai-generated", "stable diffusion", "midjourney", "dall-e", "generated by ai")


def fetch(url: str, limit: int = 12_000_000) -> bytes:
    p = urlsplit(url)
    if p.scheme != "https" or p.username or p.password or p.fragment or p.port not in (None, 443):
        raise ValueError("Solo HTTPS sin credenciales ni puertos extraños")
    if p.hostname not in ("commons.wikimedia.org", "upload.wikimedia.org", "thumb.wikimedia.org", "www.google.com"):
        raise ValueError("Host multimedia no autorizado")
    request = Request(url, headers={"User-Agent": "ORBIUNO-Newsroom/1.0 (media rights audit; contact via project GitHub)"})
    with urlopen(request, timeout=38) as response:
        final = urlsplit(response.url)
        commons_hosts = {"commons.wikimedia.org", "upload.wikimedia.org", "thumb.wikimedia.org"}
        # Solo los favicons de Google pueden redirigir a las CDN oficiales gstatic.
        google_favicon_hosts = {"www.google.com", "www.gstatic.com", "t0.gstatic.com", "t1.gstatic.com",
                                "t2.gstatic.com", "t3.gstatic.com", "encrypted-tbn0.gstatic.com",
                                "encrypted-tbn1.gstatic.com", "encrypted-tbn2.gstatic.com", "encrypted-tbn3.gstatic.com"}
        if p.hostname == "www.google.com" and p.path == "/s2/favicons":
            destinations = google_favicon_hosts
        elif p.hostname in commons_hosts:
            destinations = commons_hosts
        else:
            destinations = {"www.google.com"}
        if final.scheme != "https" or final.hostname not in destinations or final.port not in (None, 443):
            raise ValueError("Redireccion fuera de hosts autorizados: " + str(final.hostname or "sin_host"))
        raw = response.read(limit + 1)
    if not raw or len(raw) > limit:
        raise ValueError("Multimedia vacio o mayor al límite")
    return raw


def clean(value: str) -> str:
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]*>", " ", str(value or "")))).strip()


def commons_info(title: str, getter=fetch) -> dict:
    if not isinstance(title, str) or not re.fullmatch(r"File:[^<>\r\n]{5,190}", title):
        raise ValueError("Falta título exacto File:... de Commons")
    query = urlencode({"action": "query", "titles": title, "prop": "imageinfo",
                       "iiprop": "url|size|extmetadata|mime", "iiurlwidth": "1280", "format": "json"})
    data = json.loads(getter("https://commons.wikimedia.org/w/api.php?" + query))
    pages = list(data.get("query", {}).get("pages", {}).values())
    if len(pages) != 1 or "missing" in pages[0]:
        raise ValueError("Archivo de Commons no existe")
    page = pages[0]
    info = (page.get("imageinfo") or [{}])[0]
    meta = info.get("extmetadata", {})
    m = lambda name: clean((meta.get(name) or {}).get("value", ""))
    lic = m("LicenseShortName")
    if lic not in LICENSES:
        raise ValueError("Licencia no aprobada o desconocida: " + lic[:65])
    artist = m("Artist")
    if not artist or artist.lower() in ("unknown", "autor desconocido", "uncredited"):
        raise ValueError("Autor no identificado")
    if info.get("mime") not in ("image/jpeg", "image/png") or info.get("width", 0) < 650 or info.get("height", 0) < 450:
        raise ValueError("Foto no es JPG/PNG o resolucion insuficiente")
    note = " ".join((page.get("title", ""), m("ImageDescription"), m("Categories"))).lower()
    if any(tag in note for tag in BAD_TAGS):
        raise ValueError("Fotografia posiblemente sintetica, rechazada")
    url = info.get("thumburl") or info.get("url")
    if not url or urlsplit(url).hostname not in ("upload.wikimedia.org", "thumb.wikimedia.org"):
        raise ValueError("Archivo no alojado en Wikimedia")
    return {"title": page["title"], "license": lic, "author": artist[:180],
            "page": "https://commons.wikimedia.org/wiki/" + quote(page["title"].replace(" ", "_"), safe="/:()'- ,".replace(" ","")),
            "url": url, "description": m("ImageDescription")[:260]}


def decode_image(raw: bytes, *, min_size=(650, 450)) -> Image.Image:
    im = Image.open(io.BytesIO(raw))
    im.load()
    if im.format not in ("JPEG", "PNG") or im.width < min_size[0] or im.height < min_size[1]:
        raise ValueError("Imagen inválida, demasiado pequeña o formato no permitido")
    return im.convert("RGB")


def validate_editorial_photo(n: dict) -> str:
    title = n.get("photoCommonsTitle")
    if not title or n.get("photoMatchReviewed") is not True:
        raise ValueError("Falta foto real seleccionada y revisión de correspondencia")
    if not isinstance(n.get("photoCaption"), str) or len(n["photoCaption"].strip()) < 10:
        raise ValueError("Falta descripción fiel y específica de la fotografía")
    return title


def stage(edition_path: Path, news_path: Path, output: Path, *, getter=fetch) -> dict:
    edition = json.loads(edition_path.read_text(encoding="utf-8"))
    day, slot = edition["editionDate"], edition["editionSlot"]
    if edition.get("sourceOnly") is not False:
        raise ValueError("source_only no se transforma en revision editorial: BLOQUEADO")
    if day != datetime.now(ZoneInfo("America/Bogota")).date().isoformat():
        raise ValueError("No se procesa una edición de otra fecha")
    if slot not in ("08:00", "09:30", "18:00", "12:00", "19:00") or len(edition.get("news", [])) != 6:
        raise ValueError("Edición o franja incorrecta")
    db = json.loads(news_path.read_text(encoding="utf-8"))
    items = {x.get("id"): x for x in db["news"]}
    candidates = sorted(edition["news"], key=lambda n: n["priority"])
    plans = []
    for n in candidates:
        title = validate_editorial_photo(n)
        target = items.get(n["id"])
        if target is None or target.get("verification") != "editorial_verified":
            raise ValueError("Una noticia no esta verificada en noticias.json")
        first = n["sources"][0]
        p = urlsplit(first["url"])
        if p.scheme != "https" or not p.hostname or p.hostname in ("news.google.com", "www.google.com"):
            raise ValueError("Fuente original incorrecta")
        plans.append((n, commons_info(title, getter=getter), p.hostname))
    output.mkdir(parents=True, exist_ok=True)
    entries = []
    for i, (n, credit, host) in enumerate(plans, 1):
        photo = decode_image(getter(credit["url"]))
        filename = f"photo-{i:02d}.jpg"
        photo.save(output / filename, quality=88, optimize=True)
        logo_url = "https://www.google.com/s2/favicons?" + urlencode({"domain": host, "sz": 256})
        logo_raw = getter(logo_url)
        logo = Image.open(io.BytesIO(logo_raw))
        logo.load()
        if logo.width < 32 or logo.height < 32:
            raise ValueError("No hay icono legítimo legible para fuente: " + host)
        logo = logo.convert("RGBA")
        logo.save(output / f"logo-{i:02d}.png")
        entries.append({"id": n["id"], "photoFile": filename,
                        "logoFile": f"logo-{i:02d}.png", "sourceHost": host,
                        "caption": n["photoCaption"].strip(), "credit": credit})
    base = "./" + output.relative_to(ROOT).as_posix() + "/"
    for ent in entries:
        n = items[ent["id"]]
        n.update(imageUrl=base + ent["photoFile"], imageType="licensed_press_photo",
                 imageRightsVerified=True, imageSourceUrl=ent["credit"]["page"],
                 imageCredit=ent["credit"]["author"], imageLicense=ent["credit"]["license"],
                 imageCaption=ent["caption"], imageAlt=ent["caption"])
    news_path.write_text(json.dumps(db, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    result = {"edition": day, "slot": slot, "visualMode": "verified_real_photos",
              "photosCount": 6, "logosCount": 6, "entries": entries}
    (output / "credits.json").write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return result


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--edition", required=True)
    ap.add_argument("--news", default=str(ROOT / "noticias.json"))
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    result = stage(Path(args.edition).resolve(), Path(args.news).resolve(), Path(args.out).resolve())
    print("PHOTOS_AND_SOURCE_LOGOS_VERIFIED", result["photosCount"], result["logosCount"])


if __name__ == "__main__":
    main()
